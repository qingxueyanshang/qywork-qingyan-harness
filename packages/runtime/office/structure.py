"""read 的结构提取与三种格式的机械检查。

结构提取供模型阅读：段落、表格、形状、单元格等的位置与内容，输出紧凑文本。
机械检查只报告能从文件本身证明的事实；遮挡与溢出等需要查看页面才能判断的问题，只给出「疑似」级别。
"""

import re
import zipfile

from lxml import etree

from com import XL_ERROR_NAMES

W = "http://schemas.openxmlformats.org/wordprocessingml/2006/main"
WP = "http://schemas.openxmlformats.org/drawingml/2006/wordprocessingDrawing"
EMU_PER_CM = 360000
EMU_PER_TWIP = 635

XL_ERROR_TEXTS = set(XL_ERROR_NAMES.values())
VOLATILE = re.compile(r"\b(NOW|TODAY|RAND|RANDBETWEEN|OFFSET|INDIRECT)\s*\(", re.I)


def _cm(emu):
    return None if emu is None else round(emu / EMU_PER_CM, 2)


def _clip(text, n=200):
    text = " ".join((text or "").split())
    return text if len(text) <= n else text[:n] + "…"


def _parse_range(rng):
    if not rng:
        return None
    # 段落号可带 read 输出中的 P 前缀（P62-P72）。
    m = re.fullmatch(r"\s*[Pp]?(\d+)\s*(?:-\s*[Pp]?(\d+))?\s*", str(rng))
    if not m:
        return None
    a = int(m.group(1))
    return (a, int(m.group(2)) if m.group(2) else a)


# 文档库写入文档属性的默认值：python-docx 的作者与备注、python-pptx 的最后修改者与备注、openpyxl 的创建者。
LIBRARY_DEFAULTS = {"python-docx", "python-pptx", "openpyxl", "Steve Canny"}
LIBRARY_NOTES = ("generated by python-docx", "generated using python-pptx")


def check_metadata(path):
    """文档属性仍为生成库的默认值时报告：这些值会显示在文件属性与办公软件的信息面板中。"""
    dc, cp = "http://purl.org/dc/elements/1.1/", \
        "http://schemas.openxmlformats.org/package/2006/metadata/core-properties"
    try:
        with zipfile.ZipFile(path) as z:
            core = etree.fromstring(z.read("docProps/core.xml"))
    except (KeyError, zipfile.BadZipFile, etree.XMLSyntaxError):
        return []
    found = []
    for tag, label in ((f"{{{dc}}}creator", "作者"), (f"{{{cp}}}lastModifiedBy", "最后修改者"),
                       (f"{{{dc}}}description", "备注")):
        el = core.find(tag)
        value = (el.text or "").strip() if el is not None else ""
        if value in LIBRARY_DEFAULTS or value.startswith(LIBRARY_NOTES):
            found.append(f"{label}「{value}」")
    if not found:
        return []
    return [{"level": "warning", "code": "library_metadata",
             "message": f"文档属性是生成库的默认值：{'、'.join(found)}；改为真实作者或清空"}]


SHOWN_PER_CODE = 5


def _condense(checks):
    """同一类检查超过 SHOWN_PER_CODE 条时只保留前几条，并追加一条总数，避免结果被同类提示占满。"""
    out, seen, total = [], {}, {}
    for c in checks:
        total[c["code"]] = total.get(c["code"], 0) + 1
    for c in checks:
        n = seen[c["code"]] = seen.get(c["code"], 0) + 1
        if n <= SHOWN_PER_CODE:
            out.append(c)
        elif n == SHOWN_PER_CODE + 1:
            out.append({"level": c["level"], "code": c["code"],
                        "message": f"同类（{c['code']}）另有 {total[c['code']] - SHOWN_PER_CODE} 处未列出"})
    return out


def check(path, fmt):
    checks = {"docx": check_docx, "pptx": check_pptx, "xlsx": check_xlsx}[fmt](path)
    return _condense(checks + check_metadata(path))


def read(path, fmt, rng=None):
    text = {"docx": read_docx, "pptx": read_pptx, "xlsx": read_xlsx}[fmt](path, rng)
    checks = check(path, fmt)
    if checks:
        text += "\n\n检查：\n" + "\n".join(f"- [{c['level']}] {c['message']}" for c in checks)
    return text, checks


